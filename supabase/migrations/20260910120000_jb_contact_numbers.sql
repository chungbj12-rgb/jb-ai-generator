-- 지침관리(prompt_guidelines.naver)에 남아 있던 옛 번호 010-3397-5866 을 제거하고
-- "다른 번호 절대 금지" 규칙을 명시한다. (코드 상수 JB_CENTER_INFO.mobile 도 같은 커밋에서 교체)

UPDATE prompt_guidelines
SET content = replace(
      replace(
        replace(
          content,
          '   - ☎ 010-3397-5866 · "긴 글 읽어주셔서 감사합니다."',
          '   - ☎ 031-266-5779 / 010-6513-5779 · "긴 글 읽어주셔서 감사합니다."'
        ),
        '- 010-3397-5866 필수 (글 마지막 연락처) · CTA 자연스럽게',
        '- 문의 전화번호는 031-266-5779 / 010-6513-5779 두 개만 사용 (다른 010 번호·지어낸 번호 절대 금지) · 글 마지막 연락처 필수 · CTA 자연스럽게'
      ),
      '010-3397-5866',
      '010-6513-5779'
    ),
    updated_at = NOW()
WHERE platform = 'naver'
  AND content LIKE '%010-3397-5866%';
